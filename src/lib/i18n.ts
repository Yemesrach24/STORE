export const translations = { en, am, ko };

export type TranslationKey = keyof typeof en;

export type TranslationVars = Record<string, string | number>;

/** Replace `{name}` placeholders in a translated string. */
export function format(template: string, vars?: TranslationVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    vars[key] !== undefined ? String(vars[key]) : match
  );
}

export function translate(lang: Lang, key: TranslationKey, vars?: TranslationVars): string {
  const dict = translations[lang] || translations.en;
  const template = (dict[key] as string) ?? (translations.en[key] as string) ?? (key as string);
  return format(template, vars);
}
